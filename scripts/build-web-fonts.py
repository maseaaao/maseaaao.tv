"""Build content-addressed WOFF2 fonts without changing glyphs or variable axes.

Requires fonttools[woff]: python3 -m pip install 'fonttools[woff]'.
Run from any directory: python3 scripts/build-web-fonts.py.
Keep previous hashed files available for cached pages referencing older versions.
"""

from hashlib import sha256
from io import BytesIO
from pathlib import Path
import re

from fontTools.ttLib import TTFont


root = Path(__file__).resolve().parent.parent
assets = root / "dist/assets/cyber-monolith"
output = assets / "fonts"
output.mkdir(exist_ok=True)
names = {}

for family in ("Unbounded", "Geologica"):
    font = TTFont(assets / f"{family}.ttf", recalcTimestamp=False)
    font.flavor = "woff2"
    buffer = BytesIO()
    font.save(buffer)
    content = buffer.getvalue()
    name = f"{family}.{sha256(content).hexdigest()[:16]}.woff2"
    (output / name).write_bytes(content)
    names[family] = name
    font.close()
    print(f"{name}: {len(content)} bytes")

tokens = assets / "tokens.css"
css = tokens.read_text()
for family, name in names.items():
    face = (
        f"@font-face{{font-family:{family};src:url('./fonts/{name}') "
        "format('woff2');font-weight:100 900;font-display:swap}"
    )
    css, count = re.subn(r"@font-face\{font-family:" + family + r";[^}]+\}", face, css)
    if count != 1:
        raise ValueError(f"Expected one font face for {family}, got {count}")
tokens.write_text(css)

html = root / "dist/index.html"
source = html.read_text()
preloads = "\n".join(
    f'    <link rel="preload" href="assets/cyber-monolith/fonts/{name}" '
    'as="font" type="font/woff2" crossorigin="anonymous" />'
    for name in names.values()
)
start = "    <!-- Critical fonts: generated by scripts/build-web-fonts.py -->"
end = "    <!-- /Critical fonts -->"
block = f"{start}\n{preloads}\n{end}"
if start in source:
    source, count = re.subn(re.escape(start) + r".*?" + re.escape(end), block, source, flags=re.S)
    if count != 1:
        raise ValueError("Expected one critical font preload block")
else:
    marker = '    <link rel="stylesheet" href="assets/site.css" />'
    if source.count(marker) != 1:
        raise ValueError("Expected one landing stylesheet link")
    source = source.replace(marker, block + "\n" + marker)
html.write_text(source)
